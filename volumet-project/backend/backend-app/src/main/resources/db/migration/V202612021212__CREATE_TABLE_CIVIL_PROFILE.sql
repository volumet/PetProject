IF NOT EXISTS (
    SELECT 1
    FROM sys.objects
    WHERE object_id = OBJECT_ID(N'school.CIVIL_PROFILE')
)
BEGIN
    CREATE TABLE school.CIVIL_PROFILE (
        ID BIGINT PRIMARY KEY,
        STATUS NVARCHAR(6) NOT NULL,
        SOCIAL_ID NVARCHAR(20) NOT NULL,
        DATE_OF_BIRTH DATE NOT NULL,
        EMAIL NVARCHAR(50),
        PHONE_NUMBER NVARCHAR(20),

        -- Auditable
        USR_LOG_I NVARCHAR(100) NOT NULL,
        DTE_LOG_I DATETIME2 NOT NULL,
        USR_LOG_U NVARCHAR(100) NULL,
        DTE_LOG_U DATETIME2 NULL,
        VERSION BIGINT NOT NULL,

        -- Constraints
        CONSTRAINT UK_PERSON_SOCIAL_ID UNIQUE (SOCIAL_ID)
    );
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_CIVIL_PROFILE_SOCIAL_ID'
      AND object_id = OBJECT_ID('school.CIVIL_PROFILE')
)
BEGIN
    CREATE NONCLUSTERED INDEX IX_CIVIL_PROFILE_SOCIAL_ID
    ON school.CIVIL_PROFILE(SOCIAL_ID);
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.sequences
    WHERE name = 'CIVIL_PROFILE_SEQUENCE'
      AND SCHEMA_NAME(schema_id) = 'school'
)
BEGIN
    CREATE SEQUENCE school.CIVIL_PROFILE_SEQUENCE
        AS INT
        START WITH 1
        INCREMENT BY 50
        NO CYCLE;
END;