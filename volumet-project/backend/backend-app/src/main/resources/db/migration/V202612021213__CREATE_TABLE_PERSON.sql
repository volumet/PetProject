IF NOT EXISTS (
    SELECT 1
    FROM sys.objects
    WHERE object_id = OBJECT_ID(N'school.PERSON')
)
BEGIN
    CREATE TABLE school.PERSON (
        ID BIGINT PRIMARY KEY,
        UUID UNIQUEIDENTIFIER
            CONSTRAINT DF_PERSON_UUID DEFAULT NEWSEQUENTIALID(),
        STATUS NVARCHAR(6) NOT NULL,
        FIRST_NAME NVARCHAR(20) NOT NULL,
        LAST_NAME NVARCHAR(20) NOT NULL,
        PROFILE_ID BIGINT,

        -- Auditable
        USR_LOG_I NVARCHAR(100) NOT NULL,
        DTE_LOG_I DATETIME2 NOT NULL,
        USR_LOG_U NVARCHAR(100) NULL,
        DTE_LOG_U DATETIME2 NULL,
        VERSION BIGINT NOT NULL,

        -- Constraints
        CONSTRAINT UK_PERSON_PROFILE_ID UNIQUE (PROFILE_ID),
        CONSTRAINT FK_PERSON_CIVIL_PROFILE FOREIGN KEY (PROFILE_ID) REFERENCES school.PERSON(ID),
    );
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.sequences
    WHERE name = 'PERSON_SEQUENCE'
      AND SCHEMA_NAME(schema_id) = 'school'
)
BEGIN
    CREATE SEQUENCE school.PERSON_SEQUENCE
        AS INT
        START WITH 1
        INCREMENT BY 50
        NO CYCLE;
END;