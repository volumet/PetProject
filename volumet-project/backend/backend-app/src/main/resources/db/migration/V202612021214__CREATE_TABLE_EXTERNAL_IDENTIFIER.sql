IF NOT EXISTS (
    SELECT 1
    FROM sys.objects
    WHERE object_id = OBJECT_ID(N'school.EXTERNAL_IDENTIFIER')
)
BEGIN
    CREATE TABLE school.EXTERNAL_IDENTIFIER (
        ID BIGINT PRIMARY KEY,
        STATUS NVARCHAR(6) NOT NULL,
        ISSUER NVARCHAR(50) NOT NULL,
        SUBJECT NVARCHAR(50) NOT NULL,
        PERSON_ID BIGINT NOT NULL,

        -- Auditable
        USR_LOG_I NVARCHAR(100) NOT NULL,
        DTE_LOG_I DATETIME2 NOT NULL,
        USR_LOG_U NVARCHAR(100) NULL,
        DTE_LOG_U DATETIME2 NULL,
        VERSION BIGINT NOT NULL,

        -- Constraints
        CONSTRAINT FK_EXTERNAL_IDENTIFIER_PERSON FOREIGN KEY (PERSON_ID) REFERENCES school.PERSON(ID),
        CONSTRAINT UK_EXTERNAL_IDENTIFIER_ISSUER_SUBJECT UNIQUE (ISSUER, SUBJECT)
    );
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_EXTERNAL_IDENTIFIER_PERSON_ID'
      AND object_id = OBJECT_ID('school.EXTERNAL_IDENTIFIER')
)
BEGIN
    CREATE NONCLUSTERED INDEX IX_EXTERNAL_IDENTIFIER_PERSON_ID ON school.EXTERNAL_IDENTIFIER(PERSON_ID);
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.sequences
    WHERE name = 'EXTERNAL_IDENTIFIER_SEQUENCE'
      AND SCHEMA_NAME(schema_id) = 'school'
)
BEGIN
    CREATE SEQUENCE school.EXTERNAL_IDENTIFIER_SEQUENCE
        AS INT
        START WITH 1
        INCREMENT BY 50
        NO CYCLE;
END;