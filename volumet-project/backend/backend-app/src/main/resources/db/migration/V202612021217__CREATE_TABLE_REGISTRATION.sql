IF NOT EXISTS (
    SELECT 1
    FROM sys.objects
    WHERE object_id = OBJECT_ID(N'school.REGISTRATION')
)
BEGIN
    CREATE TABLE school.REGISTRATION (
        ID BIGINT PRIMARY KEY,
        STUDENT_ID BIGINT,
        ROOM_ID BIGINT,
        ISSUED_DATE DATE NOT NULL,
        EXPIRED_DATE DATE NOT NULL,
        STATUS NVARCHAR(6) NOT NULL,

        -- Auditable
        USR_LOG_I NVARCHAR(100) NOT NULL,
        DTE_LOG_I DATETIME2 NOT NULL,
        USR_LOG_U NVARCHAR(100) NULL,
        DTE_LOG_U DATETIME2 NULL,
        VERSION BIGINT NOT NULL,

        -- Constraints
        CONSTRAINT CK_REGISTRATION_DATE_ORDER CHECK (EXPIRED_DATE >= ISSUED_DATE),
        CONSTRAINT FK_REGISTRATION_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES school.STUDENT(ID),
        CONSTRAINT FK_REGISTRATION_ROOM FOREIGN KEY (ROOM_ID) REFERENCES school.ROOM(ID)
    );
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_REGISTRATION_STUDENT_ID'
      AND object_id = OBJECT_ID('school.REGISTRATION')
)
BEGIN
    CREATE NONCLUSTERED INDEX IX_REGISTRATION_STUDENT_ID ON school.REGISTRATION(STUDENT_ID);
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_REGISTRATION_ROOM_ID'
      AND object_id = OBJECT_ID('school.REGISTRATION')
)
BEGIN
    CREATE NONCLUSTERED INDEX IX_REGISTRATION_ROOM_ID ON school.REGISTRATION(ROOM_ID);
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.sequences
    WHERE name = 'REGISTRATION_SEQUENCE'
      AND SCHEMA_NAME(schema_id) = 'school'
)
BEGIN
    CREATE SEQUENCE school.REGISTRATION_SEQUENCE
        AS BIGINT
        START WITH 1
        INCREMENT BY 50
        NO CYCLE;
END;